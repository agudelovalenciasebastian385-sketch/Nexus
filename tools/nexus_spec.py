def S(sub, name, purpose, roles, methods, rules=(), validations=(), exceptions=(), outports=(), uses=(),
      audit=()):
    return dict(sub=sub, name=name, purpose=purpose, roles=roles, methods=methods, rules=list(rules),
                validations=list(validations), exceptions=list(exceptions), outports=list(outports),
                uses=list(uses), audit=list(audit))


def M(ret, name, params, ports=(), doc=""):
    return dict(ret=ret, name=name, params=params, ports=list(ports), doc=doc)


