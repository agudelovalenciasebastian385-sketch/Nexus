package nexusmarket.domain.services.returns;

import lombok.RequiredArgsConstructor;
import nexusmarket.domain.exceptions.EntityNotFoundException;
import nexusmarket.domain.models.Refund;
import nexusmarket.domain.models.ReturnRequest;
import nexusmarket.domain.models.User;
import nexusmarket.domain.ports.out.RefundRepositoryPort;
import nexusmarket.domain.ports.out.ReturnRequestRepositoryPort;
import nexusmarket.domain.services.authorization.ValidateBuyerOwnershipService;
import nexusmarket.domain.services.authorization.ValidateRoleAuthorizationService;
import nexusmarket.domain.valueobjects.SystemRole;
import org.springframework.stereotype.Service;

/**
 * Retrieves a return request or the refund generated by it
 * (returns-services.md - ConsultReturn). A buyer only consults returns of its
 * own orders.
 */
@Service
@RequiredArgsConstructor
public class ConsultReturnService {

    private final ReturnRequestRepositoryPort returnRequestRepositoryPort;
    private final RefundRepositoryPort refundRepositoryPort;
    private final ValidateRoleAuthorizationService validateRoleAuthorizationService;
    private final ValidateBuyerOwnershipService validateBuyerOwnershipService;

    public ReturnRequest consultReturn(User requestingUser, String returnRequestId) {
        User requester = authorize(requestingUser);
        return loadAccessibleReturn(requester, returnRequestId);
    }

    public Refund consultRefund(User requestingUser, String returnRequestId) {
        User requester = authorize(requestingUser);
        ReturnRequest returnRequest = loadAccessibleReturn(requester, returnRequestId);
        return refundRepositoryPort.findByReturnRequest(returnRequest)
                .orElseThrow(() -> new EntityNotFoundException("Refund", "return request " + returnRequestId));
    }

    private User authorize(User requestingUser) {
        return validateRoleAuthorizationService.execute(requestingUser, SystemRole.BUYER,
                SystemRole.ADMINISTRATOR, SystemRole.SUPERVISOR);
    }

    private ReturnRequest loadAccessibleReturn(User requester, String returnRequestId) {
        ReturnRequest returnRequest = returnRequestRepositoryPort.findById(returnRequestId)
                .orElseThrow(() -> new EntityNotFoundException("ReturnRequest", returnRequestId));
        validateBuyerOwnershipService.execute(requester, returnRequest.getOrder());
        return returnRequest;
    }
}
